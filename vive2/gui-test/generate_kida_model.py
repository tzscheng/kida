#!/usr/bin/env python3
"""Embed KIDA's YAML geometry and controller joint-command bounds in C++.

The generated header ships with the app. Runtime needs neither Python nor YAML.
Unchanged inputs only require Python's standard library during a rebuild.
"""
import ast
import hashlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
KIDA = HERE.parent.parent
MODEL = KIDA / "yaml/kida.yaml"
CONTROL = KIDA / "kida.py"
OUTPUT = HERE / "kida_model_data.h"


def literal(node):
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Mult):
        return literal(node.left) * literal(node.right)
    return ast.literal_eval(node)


def main():
    if not MODEL.exists() or not CONTROL.exists():
        if OUTPUT.exists():
            print("Using bundled KIDA model (source repository absent).")
            return
        raise SystemExit("Missing KIDA YAML/controller and generated model header")
    digest = hashlib.sha256(MODEL.read_bytes() + CONTROL.read_bytes()).hexdigest()
    if OUTPUT.exists() and f"// Source SHA256: {digest}" in OUTPUT.read_text():
        return
    import yaml

    bodies = {b["name"]: b for b in yaml.safe_load(MODEL.read_text())["bodies"]}
    values = {}
    for node in ast.walk(ast.parse(CONTROL.read_text())):
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            key = target.id if isinstance(target, ast.Name) else (
                target.attr if isinstance(target, ast.Attribute) else "")
            if key in ("lo", "hi", "init2", "home_task") and key not in values:
                try:
                    value = literal(node.value)
                    if len(value) in (12, 14):
                        values[key] = value
                except (ValueError, TypeError):
                    pass
    assert all(k in values for k in ("lo", "hi", "init2", "home_task"))

    def numbers(items):
        return "{" + ",".join(format(float(x), ".17g") for x in items) + "}"

    def pose(spec):
        if spec.get("eulerseq", "XYZ") != "XYZ":
            raise ValueError("KIDA generator expects intrinsic XYZ")
        return "{" + numbers(spec.get("pos", [0]*3)) + "," + numbers(spec.get("euler", [0]*3)) + "}"

    lines = ["// Generated by generate_kida_model.py; do not edit.",
             f"// Source SHA256: {digest}", "#pragma once", "#include <array>",
             "namespace kida::model {",
             "struct Offset { std::array<double,3> position, euler_degrees; };",
             "struct Joint { Offset offset; double low, high; };",
             "struct Shape { int body; Offset offset; double radius, half_length; };",
             "// Bounds from kida.py joint command clamps, not YAML mechanical limits."]
    for side, start in enumerate((1, 8)):
        joints = [bodies[f"link{i}"] for i in range(start, start+7)]
        tcp = bodies[f"tcp{side+1}"]
        lines.append(f"inline constexpr std::array<Joint,7> joints{side} = {{{{")
        parent = "root"
        for j, b in enumerate(joints):
            spec = b["joint"]
            assert spec["type"] == "rev" and spec["parent"] == parent
            index = 7*side+j
            lines.append("{" + pose(spec) + f",{values['lo'][index]},{values['hi'][index]}" + "},")
            parent = b["name"]
        assert tcp["joint"]["parent"] == parent and tcp["joint"]["type"] == "fixed"
        lines += ["}};", f"inline constexpr Offset tcp{side} = {pose(tcp['joint'])};",
                  f"inline constexpr std::array<double,7> seed{side} = {numbers(values['init2'][side*7:side*7+7])};",
                  f"inline constexpr std::array<double,6> home{side} = {numbers(values['home_task'][side*6:side*6+6])};"]
        shapes = []
        for index, body in enumerate(joints+[tcp]):
            for shape in body.get("shapes", []):
                assert shape["type"] == "cylinder"
                radius, half = shape["param"]
                shapes.append("{" + str(index) + "," + pose(shape) + f",{radius},{half}" + "},")
        lines += [f"inline constexpr std::array<Shape,{len(shapes)}> shapes{side} = {{{{", *shapes, "}};"]
    lines += ["} // namespace kida::model", ""]
    OUTPUT.write_text("\n".join(lines))
    print("Generated kida_model_data.h from ../../yaml/kida.yaml and ../../kida.py")


if __name__ == "__main__":
    main()
